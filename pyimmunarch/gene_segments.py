# Map of species aliases -> full names recognised in .gene strings.
SPECIES_ALIAS = {
    "hs": "homosapiens",
    "homosapiens": "homosapiens",
}


def get_genes(gene: str = "hs.trbv"):
    """Return the sorted reference segment list for a ``.gene`` string.

    ``gene`` looks like ``"hs.trbv"`` / ``"HomoSapiens.TRBJ"`` — a species
    alias and a gene name separated by a dot.  Only human segments are
    bundled; unknown genes return an empty list.
    """
    parts = gene.lower().split(".")
    if len(parts) < 2:
        return []
    which = parts[1]
    segs = GENE_SEGMENTS.get(which)
    if segs is None:
        return []
    return sorted(segs.split(","))
